import assert from 'node:assert/strict';
import * as T from 'three';
import {sourceFromGeometry,context,collides,contactArea,sectionArea,withinSite,generateCandidate,arrangementHash,demoSources,PROGRAMS,analyze,serializeSource,restoreSource,snapTo} from './dist/engine.js';
const source=sourceFromGeometry(new T.BoxGeometry(10,10,10),'Test solid');
const instance=(id,x=0,y=5,z=0,scale=1)=>({id,sourceId:source.id,program:'office',name:id,position:[x,y,z],rotation:[0,0,0],scale:[scale,scale,scale],locked:false});
const a=instance('a'),face=instance('b',10),overlap=instance('c',8),nested=instance('d',0,5,0,.2);
const ctx=i=>context(i,[source]);
assert.equal(collides(ctx(a),ctx(face)),false,'Surface contact is allowed');
assert.equal(collides(ctx(a),ctx(overlap)),true,'Partial overlap detected');
assert.equal(collides(ctx(a),ctx(nested)),true,'Fully contained overlap detected');
assert.equal(collides(ctx(a),ctx(a)),true,'Coincident solids detected');
const area=contactArea(ctx(a),source.ports.find(p=>p.id==='East'),ctx(face),source.ports.find(p=>p.id==='West'));
assert.ok(Math.abs(area-100)<.01,'Face contact area uses actual faces');
assert.ok(Math.abs(sectionArea(ctx(a),4)-100)<.01,'Horizontal section area');
const site={width:100,depth:250,boundary:[[-50,-125],[50,-125],[50,125],[-50,125]],exclusions:[],setback:3,maxHeight:42,entrance:[-50,75]};
assert.equal(withinSite(ctx(instance('out',60)),site),false,'Out-of-site mass rejected');
const rules={gap:6,slide:12,minAngle:0,maxAngle:270,angleStep:90,minScale:.9,maxScale:1.1,autoBridges:true,requireConnected:false,allowOverlap:false,allowTilt:false,minContact:8,minEdge:2,corridorWidth:3,corridorHeight:3.5,bridgeReach:26,weights:{program:35,circulation:30,open:15,views:20}};
const floating=analyze([instance('up',0,30)], [source],site,rules,PROGRAMS);
assert.ok(floating.warnings.some(w=>w.code==='support'),'Floating mass warning');
assert.ok(floating.warnings.some(w=>w.code==='circulation'),'Disconnected elevated mass warning');
const snapped=snapTo(instance('moving',30),'West',a,'East',[source],0);
assert.ok(Math.abs(snapped.position[0]-10)<.01,'Face snap translation');
const restored=restoreSource(serializeSource(source));
assert.deepEqual([...restored.geometry.attributes.position.array],[...source.geometry.attributes.position.array],'Serialized geometry preserved');
assert.deepEqual(restored.ports,source.ports,'Serialized anchors preserved');
const sources=demoSources();let start=performance.now();
const g1=generateCandidate(sources,site,rules,42,'Research spine');
const g2=generateCandidate(sources,site,rules,42,'Research spine');
assert.ok(g1.ok,JSON.stringify(g1));
assert.equal(arrangementHash(g1.instances),arrangementHash(g2.instances),'Deterministic seed');
const lock={...g1.instances[0],locked:true};
const g3=generateCandidate(sources,site,rules,7941,'Research spine',[lock]);
assert.ok(g3.ok,JSON.stringify(g3));assert.deepEqual(g3.instances.find(i=>i.id===lock.id),lock,'Locked transform preserved');
const result=analyze(g1.instances,sources,site,rules,PROGRAMS);
console.log(JSON.stringify({checks:'all passed',elapsedMs:Math.round(performance.now()-start),instances:g1.instances.length,metrics:result.metrics,warnings:result.warnings.length},null,2));
